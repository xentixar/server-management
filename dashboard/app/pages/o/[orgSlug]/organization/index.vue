<script setup lang="ts">
import * as z from 'zod'
import type { FormSubmitEvent } from '@nuxt/ui'
import { ApiError } from '~/utils/api'
import { Ability } from '~/utils/auth/abilities'

const { selected, updateSelected, removeSelected, pending } = useOrganizations()
const { can } = useGate()
const toast = useToast()
const deleteOpen = ref(false)
const deleting = ref(false)

const orgSchema = z.object({
  name: z.string().min(5, 'Must be at least 5 characters')
})

type OrgSchema = z.output<typeof orgSchema>

const state = reactive<Partial<OrgSchema>>({
  name: selected.value?.name
})

watch(selected, (org) => {
  state.name = org?.name
}, { deep: true })

async function onSubmit(event: FormSubmitEvent<OrgSchema>) {
  try {
    await updateSelected(event.data.name)
    toast.add({
      title: 'Organization updated',
      description: selected.value
        ? `Slug is now ${selected.value.slug}.`
        : undefined,
      color: 'success'
    })
  } catch (error) {
    const err = error instanceof ApiError ? error : new ApiError('Update failed', 500)
    toast.add({
      title: 'Could not update organization',
      description: err.message,
      color: 'error'
    })
  }
}

async function onDeleteConfirm() {
  deleting.value = true
  try {
    await removeSelected()
    deleteOpen.value = false
    toast.add({
      title: 'Organization deleted',
      color: 'success'
    })
  } catch (error) {
    const err = error instanceof ApiError ? error : new ApiError('Delete failed', 500)
    toast.add({
      title: 'Could not delete organization',
      description: err.message,
      color: 'error'
    })
  } finally {
    deleting.value = false
  }
}
</script>

<template>
  <div
    v-if="selected"
    class="flex flex-col gap-4 sm:gap-6"
  >
    <UForm
      id="organization-general"
      :schema="orgSchema"
      :state="state"
      @submit="onSubmit"
    >
      <UPageCard
        title="General"
        description="Name for the current organization. Slug is generated by the API."
        variant="naked"
        orientation="horizontal"
        class="mb-4"
      >
        <UButton
          v-if="can(Ability.OrganizationUpdate)"
          form="organization-general"
          label="Save changes"
          color="neutral"
          type="submit"
          class="w-fit lg:ms-auto"
          :loading="pending"
        />
      </UPageCard>

      <UPageCard variant="subtle">
        <UFormField
          name="name"
          label="Name"
          description="Shown in the sidebar switcher and billing."
          required
          class="flex max-sm:flex-col items-start justify-between gap-4"
        >
          <UInput
            v-model="state.name"
            autocomplete="off"
            :readonly="!can(Ability.OrganizationUpdate)"
          />
        </UFormField>

        <USeparator />

        <UFormField
          label="Slug"
          description="URL-safe identifier. Regenerated when you rename."
          class="flex max-sm:flex-col items-start justify-between gap-4"
        >
          <UInput
            :model-value="selected.slug"
            readonly
            autocomplete="off"
          />
        </UFormField>
      </UPageCard>
    </UForm>

    <UPageCard
      v-if="can(Ability.OrganizationDelete)"
      title="Danger zone"
      description="Delete this organization and all of its servers, sites, and members. This cannot be undone."
      class="bg-linear-to-tl from-error/10 from-5% to-default"
    >
      <template #footer>
        <UButton
          label="Delete organization"
          color="error"
          @click="deleteOpen = true"
        />
      </template>
    </UPageCard>

    <OrganizationDeleteOrganizationModal
      v-if="can(Ability.OrganizationDelete)"
      v-model:open="deleteOpen"
      :organization="selected"
      :loading="deleting"
      @confirm="onDeleteConfirm"
    />
  </div>
</template>
